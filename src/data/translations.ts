export function getMissingTranslationKeys(): Partial<Record<Language, string[]>> {
  return (Object.keys(translations) as Language[]).reduce<Partial<Record<Language, string[]>>>((missing, lang) => {
    const values = translations[lang] as unknown as Record<string, unknown>;
    const referenceKeys = Object.keys(translations.en);
    const missingKeys = referenceKeys.filter((key) => {
      const value = values[key];
      if ((key === 'extra' || key === 'ui') && value && typeof value === 'object') {
        const localizedSection = value as Record<string, unknown>;
        const expectedKeys = key === 'extra' ? EXTRA_TRANSLATION_KEYS : Object.keys(UI_COPY_EN);
        return expectedKeys.some((sectionKey) => {
          const localized = localizedSection[sectionKey];
          return typeof localized !== 'string' || localized.trim() === '';
        });
      }
      return typeof value !== 'string' || value.trim() === '';
    });
    if (missingKeys.length > 0) missing[lang] = missingKeys;
    return missing;
  }, {});
}

export function uiCopy(lang: Language, key: UiCopyKey): string {
  return translations[lang].ui[key];
}

