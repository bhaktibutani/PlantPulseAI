export function cropDisplayName(lang: Language, value: string): string {
  const normalized = value.trim().toLocaleLowerCase();
  const exactId = normalized.replace(/[\s_-]+/g, '');
  const exactCrop = CROP_LABELS[exactId];
  if (exactCrop) return exactCrop[lang];

  const alias = CROP_ALIASES[normalized];
  if (alias) return CROP_LABELS[alias][lang];

  const prefix = Object.keys(CROP_ALIASES)
    .sort((a, b) => b.length - a.length)
    .find((candidate) => {
      const escaped = candidate.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      return new RegExp(`^${escaped}(?=$|[\\s:(—-])`, 'i').test(value);
    });
  if (!prefix) return value;

  const crop = CROP_LABELS[CROP_ALIASES[prefix]];
  const escaped = prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return value.replace(new RegExp(`^${escaped}`, 'i'), crop[lang]);
}

export function localizedText(lang: Language, value: string): string {
  for (const sourceLang of ['en', 'gu', 'hi'] as const) {
    const source = translations[sourceLang];
    const translated = translations[lang];
    for (const [key, text] of Object.entries(source.ui)) {
      if (text === value) return translated.ui[key as UiCopyKey];
    }
    for (const key of EXTRA_TRANSLATION_KEYS) {
      if (source.extra[key] === value) return translated.extra[key];
    }
    for (const key of Object.keys(source) as (keyof TranslationStrings)[]) {
      const sourceValue = source[key];
      if (typeof sourceValue === 'string' && sourceValue === value) {
        const translatedValue = translated[key];
        if (typeof translatedValue === 'string') return translatedValue;
      }
    }
  }

  const term = KNOWN_TERMS[value];
  if (term) return term[lang];
  const translatedCrop = cropDisplayName(lang, value);
  let localized = (translatedCrop !== value ? translatedCrop : value).replace(
    /\b(Tomatoes?|Chillies?|Chilis?|Cotton|Wheat|Groundnuts?|Peanuts?|Roses?|Tulsi|Potatoes?|Onions?|Brinjals?|Eggplants?|Cucumbers?|Mangoes?)\b/gi,
    (match) => {
      const id = CROP_ALIASES[match.toLocaleLowerCase()];
      return id ? CROP_LABELS[id][lang] : match;
    }
  );
  for (const [source, names] of Object.entries(KNOWN_TERMS)) {
    if (source !== names.en) continue;
    const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    localized = localized.replace(new RegExp(escaped, 'gi'), names[lang]);
  }
  return localized;
}

export function findUntranslatedUiLabels(lang: Language, visibleText: string[]): string[] {
  if (lang === 'en') return [];
  const englishUiValues = new Set(Object.values(translations.en.ui));
  const englishExtraValues = new Set(Object.values(translations.en.extra));
  const englishTerms = new Set([
    ...Object.keys(KNOWN_TERMS),
    ...Object.values(CROP_LABELS).map((names) => names.en),
  ]);
  return [...new Set(visibleText.filter((text) =>
    text.trim() !== '' &&
    (englishUiValues.has(text) || englishExtraValues.has(text) || englishTerms.has(text)) &&
    localizedText(lang, text) === text
  ))];
}

export function getLocalizationAudit(lang: Language, visibleText: string[]) {
  return {
    missingTranslationKeys: getMissingTranslationKeys()[lang] || [],
    untranslatedKnownUiLabels: findUntranslatedUiLabels(lang, visibleText),
  };
}
